/* Presentation regression test, usable with the repository or the uploaded ZIP base. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const { chromium } = require('playwright');
const root = process.env.SIM_ROOT || path.resolve(__dirname, '..');
(async () => {
  const server = http.createServer((req, res) => {
    let name = decodeURIComponent(req.url.split('?')[0]);
    if (name.endsWith('/')) name += 'index.html';
    const file = path.resolve(root, '.' + name);
    if (!file.startsWith(root + path.sep)) { res.writeHead(403).end(); return; }
    fs.readFile(file, (error, data) => {
      if (error) { res.writeHead(404).end(); return; }
      res.setHeader('Content-Type', ({ '.html': 'text/html', '.js': 'application/javascript', '.css': 'text/css', '.png': 'image/png', '.mp3': 'audio/mpeg' })[path.extname(file)] || 'application/octet-stream');
      res.end(data);
    });
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const browser = await chromium.launch({ executablePath: process.env.SKY_CHROMIUM || undefined, args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', r => { if (r.status() >= 400) errors.push(r.status() + ' ' + r.url()); });
  const capture = async name => {
    if (!process.env.SKY_SCREENSHOTS) return;
    fs.mkdirSync(process.env.SKY_SCREENSHOTS, { recursive: true });
    await page.waitForTimeout(450);
    await page.screenshot({ path: path.join(process.env.SKY_SCREENSHOTS, name + '.png') });
  };
  try {
    await page.goto('http://127.0.0.1:' + server.address().port + '/#pc');
    await page.waitForFunction(() => document.querySelector('.web-header') && !document.getElementById('carga'));
    assert.equal(await page.locator('#lista .paso').count(), 13);
    await page.locator('#sig').click();
    await page.waitForFunction(() => cur === 0);
    await page.locator('#dock-next').click();
    await page.waitForFunction(() => cur === 1);
    await page.locator('#lista .paso').nth(4).click();
    await page.waitForFunction(() => cur === 4);
    assert.equal(await page.locator('#lista [aria-current=step]').count(), 1);
    assert.notEqual(await page.locator('.web-sidebar-meter strong').textContent(), '0%');
    await page.evaluate(() => SKY.ocultar());
    await capture('pc-escritorio');
    await page.locator('.web-settings > summary').click();
    await page.locator('#giro-auto').click();
    assert.equal(await page.evaluate(() => ctl.autoRotate), true);
    await page.locator('#giro-auto').click();
    const accent = await page.evaluate(() => getComputedStyle(document.body).getPropertyValue('--web-red'));
    await page.locator('#rgb-color').fill('#22aa77');
    assert.equal(await page.evaluate(() => getComputedStyle(document.body).getPropertyValue('--web-red')), accent);
    await page.locator('#modo').click();
    assert.equal(await page.evaluate(() => modoManual), true);
    await page.locator('#modo').click();
    assert.equal(await page.evaluate(() => modoManual), false);
    await capture('ajustes-escritorio');
    await page.locator('#gbtn').click();
    await page.waitForFunction(() => gal);
    await page.locator('[data-web-panel=gallery] [data-id=ram]').click();
    await page.locator('#ge').click();
    assert.equal(await page.evaluate(() => gexpT), 1);
    await capture('galeria-escritorio');
    await page.locator('#gv').click();
    await page.locator('#ayu').click();
    await page.locator('#mod').waitFor();
    await page.keyboard.press('Escape');
    await page.locator('#qzb').click();
    await page.locator('#mod').waitFor();
    await page.keyboard.press('Escape');
    await page.locator('#sim-nav [data-route=laptop]').click();
    const f = page.frameLocator('#laptop-view');
    await f.locator('.web-stage').waitFor();
    const child = page.frames().find(f => f.url().includes('laptop.html'));
    await child.waitForFunction(() => window.LAPTOP_READY);
    await f.locator('#sig').click();
    await child.waitForFunction(() => paso === 0);
    assert.equal(await f.locator('#lista .paso').count(), 10);
    await child.evaluate(() => SKY.ocultar());
    await capture('laptop-escritorio');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('.web-drawer-toggle').click();
    await f.locator('[data-web-panel=assembly]').waitFor({state:'visible'});
    assert.equal(await f.locator('[data-web-panel=assembly]').isVisible(), true);
    await f.locator('#lista .paso').nth(3).click();
    await child.waitForFunction(() => paso === 3);
    await page.waitForFunction(()=>document.querySelector('.web-drawer-toggle').getAttribute('aria-expanded')==='false');
    assert.equal(await page.locator('.web-drawer-toggle').getAttribute('aria-expanded'), 'false');
    await page.locator('.web-drawer-toggle').click();
    const aula = await page.evaluate(() => SIM_AULA);
    await f.locator('[data-control=sim-aula]').click();
    await page.waitForFunction(previous => SIM_AULA !== previous, aula);
    await f.locator('.web-drawer-backdrop').click({ position: { x: 350, y: 50 } });
    await capture('laptop-movil');
    await page.locator('#sim-nav [data-route=pc]').click();
    await capture('pc-movil');
    await page.locator('.web-drawer-toggle').click();
    await capture('pasos-movil');
    await page.locator('#lista .paso').nth(1).press('Enter');
    await page.waitForFunction(()=>document.querySelector('.web-drawer-toggle').getAttribute('aria-expanded')==='false');
    assert.equal(await page.locator('.web-drawer-toggle').getAttribute('aria-expanded'), 'false');
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No horizontal page overflow');
    await page.locator('.web-brand').click();
    await capture('inicio-movil');
    assert(await page.locator('#intro-pc').isVisible());
    assert(await page.locator('#intro-laptop').isVisible());
    assert.deepEqual(errors, []);
    console.log('PASS: native steps, progress, settings, RGB, manual, gallery, help/quiz, laptop, mobile drawer, keyboard and no runtime errors.');
  } finally {
    await browser.close();
    server.close();
  }
})().catch(error => { console.error(error); process.exit(1); });
